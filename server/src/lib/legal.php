/** 未記入の項目名。空なら埋め終わっている。 @return array<int, string> */
function km_legal_placeholders(): array
{
    $labels = [
        'name' => '運営者名',
        'contact' => '問い合わせ窓口',
        'contactUrl' => '問い合わせ先 URL',
        'law' => '準拠法',
    ];

    $missing = [];
    foreach ($labels as $key => $label) {
        $value = KM_LEGAL_OPERATOR[$key] ?? null;
        if (!is_string($value) || trim($value) === '') {
            $missing[] = $label;
        }
    }

    return $missing;
}

/** 本文に差し込む運営者名。未記入なら、そうと分かる形で出す。 */
function km_legal_operator_name(): string
{
    $name = KM_LEGAL_OPERATOR['name'] ?? null;

    return is_string($name) && trim($name) !== '' ? trim($name) : '(運営者名 未記入)';
}

/** 本文に差し込む窓口名。 */
function km_legal_operator_contact(): string
{
    $contact = KM_LEGAL_OPERATOR['contact'] ?? null;

    return is_string($contact) && trim($contact) !== '' ? trim($contact) : '(問い合わせ窓口 未記入)';
}


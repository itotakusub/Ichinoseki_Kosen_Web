 * 利用規約とプライバシーポリシーの本文。terms.php / privacy.php が読む。
 *
 * ## なぜ PHP の配列に置くのか
 *
 * HTML に直接書くと、2ページで見出しの作り方や言い回しがすぐずれる。ここに置けば
 * 体裁は1つの描画関数([km_legal_render_sections])が決め、**書くのは中身だけ**になる。
 * 検査(scripts/check.php の legal)も、この構造を見て抜けを拾える。
 *
 * ## 中身は「実際に動いているもの」から書いてある
 *
 * 収集項目の表は、コードが本当に作っている表と対応させてある。ここが実装とずれると、
 * **書いてあることと違う扱いをしている**状態になり、無いより悪い。
 * 収集を増やすときは、この表も一緒に直すこと。
 *
 * | 書いてあるもの | 実体 |
 * |---|---|
 * | サインイン情報 | Logto(このサーバー内で動作) |
 * | 管理操作の記録 | `km_admin_log`(lib/admin-log.php) |
 * | 解除の失敗記録 | `km_map_unlock_attempts`(lib/map-rate-limit.php) |
 * | お問い合わせ | `km_form_submissions`(lib/forms.php) |
 * | ランキング | `km_map_ranking_*`(lib/app-ranking.php) |
 * | アプリの設定同期 | `km_app_settings`(lib/app-settings.php) |
 *
 * ## 運営者の情報は埋めること
 *
 * 学校名・担当窓口・連絡先は**こちらでは決められない**。未記入のままだと、
 * 両ページの先頭に警告が出る([km_legal_placeholders])。埋めるまでは
 * 「公開しているが、誰の文書か分からない」状態になるので、そのことを隠さない。
 */


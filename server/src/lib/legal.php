/**
 * 節を HTML にする。**エスケープはここで行う。** 呼ぶ側で忘れないようにするため。
 *
 * 本文中の `**…**` は強調にする。規約は「ここだけは読ませたい」箇所が要るが、
 * 配列に HTML を書くとエスケープの判断が呼ぶ側に散る。**記法を1つだけ許す**方が安全。
 *
 * @param array<int, array> $sections
 */
function km_legal_render_sections(array $sections): string
{
    $html = '';

    foreach ($sections as $section) {
        $html .= '<section class="km-doc-section">';
        $html .= '<h2>' . km_legal_e((string) ($section['heading'] ?? '')) . '</h2>';

        foreach (($section['paragraphs'] ?? []) as $paragraph) {
            $html .= '<p>' . km_legal_inline((string) $paragraph) . '</p>';
        }

        if (($section['table'] ?? null) !== null) {
            $html .= '<div class="km-doc-scroll"><table class="km-doc-table"><thead><tr>';
            foreach ($section['table']['head'] as $heading) {
                $html .= '<th scope="col">' . km_legal_e((string) $heading) . '</th>';
            }
            $html .= '</tr></thead><tbody>';
            foreach ($section['table']['rows'] as $row) {
                $html .= '<tr>';
                foreach ($row as $cell) {
                    $html .= '<td>' . km_legal_inline((string) $cell) . '</td>';
                }
                $html .= '</tr>';
            }
            $html .= '</tbody></table></div>';
        }

        if (($section['list'] ?? []) !== []) {
            $html .= '<ul>';
            foreach ($section['list'] as $item) {
                $html .= '<li>' . km_legal_inline((string) $item) . '</li>';
            }
            $html .= '</ul>';
        }

        $html .= '</section>';
    }

    return $html;
}

function km_legal_e(string $value): string
{
    return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/**
 * エスケープしてから `**…**` だけを `<strong>` に開く。
 *
 * **順序が重要。** 先にエスケープするので、本文に `<` や `>` が混ざっていても
 * タグにはならない。開くのは自分で作った `<strong>` だけ。
 */
function km_legal_inline(string $value): string
{
    $escaped = km_legal_e($value);

    return (string) preg_replace('/\*\*(.+?)\*\*/u', '<strong>$1</strong>', $escaped);
}

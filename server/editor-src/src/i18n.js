/** 言語を決める(?lang= → 覚えたもの → ブラウザの言語)。**純粋関数** */
export function pickLang(search, saved, browserLang) {
  const param = /[?&]lang=(en|ja)\b/.exec(String(search ?? ''));
  if (param) {
    return param[1];
  }
  if (LANGS.includes(saved)) {
    return saved;
  }
  return /^ja\b/i.test(String(browserLang ?? '')) ? 'ja' : 'en';
}

/** 訳を引く。無ければ日本語、それも無ければ鍵そのもの。{name} は vars で埋める */
export function t(lang, key, vars = {}) {
  const table = DICT[lang] ?? DICT.ja;
  const text = table[key] ?? DICT.ja[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (all, name) => (name in vars ? String(vars[name]) : all));
}

export function hasKey(lang, key) {
  return Object.prototype.hasOwnProperty.call(DICT[lang] ?? {}, key);
}

export function dictKeys(lang) {
  return Object.keys(DICT[lang] ?? {});
}

export function detectLang() {
  let saved = null;
  try {
    saved = globalThis.localStorage?.getItem(LANG_KEY) ?? null;
  } catch {
    // 覚えられない端末
  }
  return pickLang(globalThis.location?.search, saved, globalThis.navigator?.language);
}

export function rememberLang(lang) {
  try {
    globalThis.localStorage?.setItem(LANG_KEY, lang);
  } catch {
    // 覚えられなくても、この回は切り替える
  }
}

/** 殻の data-i18n* を入れ替える */
export function applyI18n(root, lang) {
  root.documentElement.lang = lang;
  root.title = t(lang, 'doc.title');
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(lang, el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(lang, el.dataset.i18nTitle);
    if (el.hasAttribute('aria-label') && !el.hasAttribute('data-i18n-aria')) {
      el.setAttribute('aria-label', t(lang, el.dataset.i18nTitle));
    }
  }
  for (const el of root.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(lang, el.dataset.i18nAria));
  }
}
